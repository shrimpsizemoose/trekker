class TestCustomTemplateDir:
    """Tests for -t/--templates flag."""

    def test_nonexistent_template_dir(self, valid_config, tmp_path):
        result = run_cli(
            "-i", str(valid_config), "-t", str(tmp_path / "nonexistent")
        )
        assert result.returncode != 0
        assert "not found" in result.stderr.lower()

    def test_custom_template_dir(self, valid_config, tmp_path):
        # Create a custom template
        template_dir = tmp_path / "templates"
        template_dir.mkdir()
        (template_dir / "base.go.j2").write_text(
            """// Custom template
package main

func main() {
    // Custom: {{ config.lab.name }}
}
"""
        )

        result = run_cli("-i", str(valid_config), "-t", str(template_dir))
        assert result.returncode == 0
        assert "// Custom template" in result.stdout
        assert "Custom: Test" in result.stdout


class TestErrorHandling:
    """Tests for error handling."""

    def test_invalid_yaml(self, tmp_path):
        config = tmp_path / "invalid.yaml"
        config.write_text("this is not valid yaml: [")
        result = run_cli("-i", str(config))
        assert result.returncode != 0
        assert "error" in result.stderr.lower() or "failed" in result.stderr.lower()

    def test_missing_required_field(self, tmp_path):
        config = tmp_path / "incomplete.yaml"
        config.write_text(
            """
lab:
  id: "01"
  # missing name and env_prefix
"""
        )
        result = run_cli("-i", str(config))
        assert result.returncode != 0

    def test_unknown_check_type(self, tmp_path):
        config = tmp_path / "bad_check.yaml"
        config.write_text(
            """
lab:
  id: "01"
  name: "Test"
  env_prefix: "TEST"
checks:
  - type: nonexistent_check_type
    foo: bar
"""
        )
        result = run_cli("-i", str(config))
        assert result.returncode != 0
