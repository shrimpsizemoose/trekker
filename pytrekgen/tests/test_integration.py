class TestRoundtripConsistency:
    """Test that multiple generations produce the same output."""

    def test_deterministic_output(self, generator):
        """Generating the same config twice should produce identical output."""
        from conftest import minimal_config

        config = minimal_config(
            checks=[
                {"type": "http_get", "url": "http://localhost:8080"},
                {
                    "type": "kafka_topic_exists",
                    "kafka_addr_env": "K",
                    "kafka_topic_env": "T",
                },
            ]
        )

        code1 = generator.generate(config, source_file="test.yaml")
        code2 = generator.generate(config, source_file="test.yaml")

        assert code1 == code2
