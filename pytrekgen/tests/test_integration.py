@pytest.mark.skipif(not has_go(), reason="Go not installed")
class TestGeneratedCodeCompiles:
    """Generated Go code should compile (requires Go installed)."""

    @pytest.mark.parametrize(
        "yaml_file",
        list(EXAMPLES_DIR.glob("*.yaml")),
        ids=lambda p: p.name,
    )
    def test_code_compiles(self, generator, yaml_file, tmp_path):
        config = generator.load_config(yaml_file)
        code = generator.generate(config)

        # Write generated code
        go_file = tmp_path / "main.go"
        go_file.write_text(code)

        # Generate go.mod if we have module info
        if config.build.module:
            gomod = tmp_path / "go.mod"
            gomod.write_text(generator.generate_gomod(config))

            # Run go mod tidy
            result = subprocess.run(
                ["go", "mod", "tidy"],
                cwd=tmp_path,
                capture_output=True,
                timeout=120,
            )
            assert result.returncode == 0, f"go mod tidy failed:\n{result.stderr.decode()}"

            # Run go build
            result = subprocess.run(
                ["go", "build", "-o", "checker", "."],
                cwd=tmp_path,
                capture_output=True,
                timeout=120,
            )
            assert result.returncode == 0, f"go build failed:\n{result.stderr.decode()}"

    def test_minimal_config_compiles(self, generator, tmp_path):
        """A minimal config should generate compilable code."""
        from conftest import minimal_config

        config = minimal_config()
        code = generator.generate(config)

        go_file = tmp_path / "main.go"
        go_file.write_text(code)

        gomod = tmp_path / "go.mod"
        gomod.write_text(generator.generate_gomod(config))

        # go mod tidy
        result = subprocess.run(
            ["go", "mod", "tidy"],
            cwd=tmp_path,
            capture_output=True,
            timeout=120,
        )
        assert result.returncode == 0, f"go mod tidy failed:\n{result.stderr.decode()}"

        # go build
        result = subprocess.run(
            ["go", "build", "-o", "checker", "."],
            cwd=tmp_path,
            capture_output=True,
            timeout=120,
        )
        assert result.returncode == 0, f"go build failed:\n{result.stderr.decode()}"


